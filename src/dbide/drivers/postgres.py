"""PostgreSQL via psycopg 3."""
from __future__ import annotations

from sqlalchemy import Connection
from sqlalchemy.engine import URL

from dbide.core.config import ConnectionConfig
from dbide.core.schema_model import ColumnDef, TableDef

from .base import Driver, GenericAlterMixin

INT_TYPES = ("INTEGER", "INT", "BIGINT", "SMALLINT", "INT4", "INT8", "INT2")


class PostgresDriver(GenericAlterMixin, Driver):
    key = "postgresql"
    label = "PostgreSQL"
    default_port = 5432
    supports_databases = True  # the tree's second level lists schemas inside the database
    container_label = "Schema"
    tree_default_schema = "public"
    ddl_transactional = True  # Postgres can roll back DDL
    named_unique_constraints = True
    explain_prefix = "EXPLAIN "
    length_fn = "OCTET_LENGTH"
    system_schemas = {"information_schema", "pg_catalog", "pg_toast"}
    common_types = [
        "INTEGER", "BIGINT", "SMALLINT", "NUMERIC(10,2)", "REAL", "DOUBLE PRECISION", "TEXT", "VARCHAR(255)",
        "BOOLEAN", "DATE", "TIMESTAMP", "TIMESTAMPTZ", "TIME", "JSONB", "UUID", "BYTEA", "INET",
    ]
    extra_keywords = ["ILIKE", "RETURNING", "SERIAL", "JSONB", "SCHEMA", "SEARCH_PATH", "ANALYZE", "VACUUM", "CONCURRENTLY",
                      "GENERATED", "IDENTITY", "ALWAYS", "ARRAY", "LATERAL", "MATERIALIZED", "OVER", "PARTITION", "WINDOW"]

    def url(self, cfg: ConnectionConfig, password: str | None) -> URL:
        host = cfg.host or "localhost"
        query = {}
        if host.startswith("/"):  # a unix-socket directory
            query["host"] = host
            host = None
        if cfg.options.get("ssl"):
            query["sslmode"] = "require"
        return URL.create("postgresql+psycopg", username=cfg.user or None, password=password or None, host=host,
                          port=(cfg.port or self.default_port) if host else None, database=cfg.database or "postgres",
                          query=query)

    def engine_kwargs(self, cfg: ConnectionConfig) -> dict:
        return {"pool_pre_ping": True, "connect_args": {"connect_timeout": 10}}

    def connection_id(self, conn: Connection):
        return conn.exec_driver_sql("SELECT pg_backend_pid()").scalar()

    def cancel(self, engine, conn: Connection, conn_id) -> None:
        with engine.connect() as other:
            other.exec_driver_sql(f"SELECT pg_cancel_backend({int(conn_id)})")

    def list_databases(self, insp) -> list[str]:
        names = [n for n in insp.get_schema_names() if not n.startswith("pg_temp") and not n.startswith("pg_toast_temp")]
        user = sorted(n for n in names if n not in self.system_schemas)
        return user + sorted(n for n in names if n in self.system_schemas)

    def use_schema_sql(self, schema: str) -> str | None:
        return f"SET search_path TO {self.quote(schema)}, public"

    def show_create(self, conn: Connection, table: str, schema: str | None) -> str:
        from sqlalchemy import inspect

        td = self.load_table_def(inspect(conn), conn, table, schema)
        return ";\n\n".join(self.create_table_sql(td)) + ";"

    def is_auto_increment(self, conn, table, schema, col) -> bool:
        default = str(col.get("default") or "")
        return bool(col.get("identity")) or default.startswith("nextval(")

    def load_table_def(self, insp, conn, table, schema) -> TableDef:
        td = super().load_table_def(insp, conn, table, schema)
        for c in td.columns:
            if c.auto_increment and (c.default or "").startswith("nextval("):
                c.default = None  # the sequence is implied by auto-increment
        pk = insp.get_pk_constraint(table, schema=schema) or {}
        td.options["pk_name"] = pk.get("name") or ""
        return td

    # ---- DDL -------------------------------------------------------------
    def column_sql(self, col: ColumnDef, td: TableDef) -> str:
        parts = [self.quote(col.name), col.type.strip()]
        if col.auto_increment:
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
        if not col.nullable or col.primary_key:
            parts.append("NOT NULL")
        if col.default not in (None, "") and not col.auto_increment:
            parts.append(f"DEFAULT {col.default.strip()}")
        return " ".join(parts)

    def create_table_body(self, td: TableDef) -> list[str]:
        lines = [self.column_sql(c, td) for c in td.columns]
        if td.primary_key:
            lines.append(f"CONSTRAINT {self.quote('pk_' + td.name)} PRIMARY KEY ({', '.join(self.quote(c) for c in td.primary_key)})")
        lines += [self.fk_sql(fk, td.schema) for fk in td.foreign_keys]
        return lines

    def create_index_sql(self, ix, td) -> str:
        cols = ", ".join(self.quote(c) for c in ix.columns)
        return f"CREATE {'UNIQUE ' if ix.unique else ''}INDEX {self.quote(ix.name)} ON {self.qualify(td.name, td.schema)} ({cols})"

    def _add_column(self, t, c, td):
        return f"ALTER TABLE {t} ADD COLUMN {self.column_sql(c, td)}"

    def _rename_column(self, td, old, new):
        return [f"ALTER TABLE {self.qualify(td.name, td.schema)} RENAME COLUMN {self.quote(old)} TO {self.quote(new)}"]

    def _rename_table(self, td, new):
        return [f"ALTER TABLE {self.qualify(td.name, td.schema)} RENAME TO {self.quote(new)}"]

    def _alter_type(self, t, ref, c):
        return [f"ALTER TABLE {t} ALTER COLUMN {ref} TYPE {c.type} USING {ref}::{c.type}"]

    def _alter_null(self, t, ref, c, nullable):
        return [f"ALTER TABLE {t} ALTER COLUMN {ref} {'DROP' if nullable else 'SET'} NOT NULL"]

    def _alter_default(self, t, td, c, o):
        ref = self.quote(c.name)
        if c.default in (None, ""):
            return [f"ALTER TABLE {t} ALTER COLUMN {ref} DROP DEFAULT"]
        return [f"ALTER TABLE {t} ALTER COLUMN {ref} SET DEFAULT {c.default}"]

    def _alter_identity(self, t, ref, c):
        if c.auto_increment:
            return [f"ALTER TABLE {t} ALTER COLUMN {ref} ADD GENERATED BY DEFAULT AS IDENTITY"]
        return [f"ALTER TABLE {t} ALTER COLUMN {ref} DROP IDENTITY IF EXISTS"]

    def _drop_pk(self, td):
        name = td.options.get("pk_name") or f"{td.name}_pkey"
        return f"ALTER TABLE {self.qualify(td.name, td.schema)} DROP CONSTRAINT {self.quote(name)}"

    def _drop_index(self, name, td):
        return f"DROP INDEX {self.qualify(name, td.schema)}"

    def truncate_table_sql(self, name: str, schema: str | None) -> str:
        return f"TRUNCATE TABLE {self.qualify(name, schema)}"

    def create_database_sql(self, name: str) -> str:
        return f"CREATE SCHEMA {self.quote(name)}"

    def drop_database_sql(self, name: str) -> str:
        return f"DROP SCHEMA {self.quote(name)} CASCADE"

    def after_explicit_ids(self, table: str, schema: str | None, column: str) -> list[str]:
        t = self.qualify(table, schema)
        # move the identity sequence past the ids we inserted ourselves
        return [f"SELECT setval(pg_get_serial_sequence({self.literal(t)}, {self.literal(column)}), "
                f"COALESCE((SELECT MAX({self.quote(column)}) FROM {t}), 1))"]
